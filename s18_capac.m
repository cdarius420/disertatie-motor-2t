% S18_CAPAC  Capacul din dreapta, modulul de putere, prinderile pe cadru, scutul.
P = parametri();
D = capac(P);
mm = 1e3;
fprintf('\n=== S18 Capacul din dreapta și prinderile ===\n');
fprintf('În lungul arborelui: carterul %.2f, urechile statorului %.2f, rotorul %.2f, fusul %.2f, bobinele %.2f mm\n', ...
        D.y_carter*mm, D.y_urechi*mm, D.y_rotor*mm, D.y_arbore*mm, D.y_bobine*mm);
fprintf('Capacul: R%.1f-%.1f mm, fața interioară la %.2f, exterioară la %.2f mm; cu modulul, motorul are %.0f mm în dreapta axei\n', ...
        D.R_int*mm, D.R_ext*mm, D.y_int*mm, D.y_ext*mm, D.latime*mm);
fprintf('Modulul: %.0f W pe mașina de pe arbore și %.0f W pe compresor -> %.0f + %.0f W pierderi; R placă %.3f K/W, h %.0f W/m2K\n', ...
        D.P_el, D.pierderi, D.R_placa, D.h);
verifica(D.joc_axial >= P.joc_rotor_capac && D.L_filet >= 1.5*5e-3, 'Q1', sprintf( ...
         'Capacul: %.0f mm radial și %.1f mm axial până la rotor și piuliță (>= %.0f); filetul M5 al statorului în bosaj %.1f mm (>= 1,5 d)', ...
         P.joc_rotor_capac*mm, D.joc_axial*mm, P.joc_rotor_capac*mm, D.L_filet*mm));
verifica(D.v_apa >= 0.5 && D.v_apa <= P.v_apa_max && D.Re >= 3000 && D.Tj <= P.Tj_max, 'Q2', sprintf( ...
         'Modulul de putere: apa %.2f m/s în cameră (Re %.0f, turbulent), joncțiunea %.0f °C cu apa la %d °C (<= %d)', ...
         D.v_apa, D.Re, D.Tj, P.T_apa_modul, P.Tj_max));
verifica(D.peste_baie >= P.perete_min && P.prindere(2) >= 6e-3 && D.perete_chiulasa >= P.prindere(2) && P.ureche_carter(3) < D.y_carter, 'Q3', sprintf( ...
         ['Prinderile: M10 cu %.0f mm de perete; urechile carterului la ±%.0f mm, %.1f mm deasupra băilor, între capace (±%.0f < %.1f); ' ...
          'urechea chiulasei cu %.2f mm până la fața ei; scutul la %.1f mm sub axă'], ...
         P.prindere(2)*mm, P.ureche_carter(1)*mm, D.peste_baie*mm, P.ureche_carter(3)*mm, D.y_carter*mm, D.perete_chiulasa*mm, -D.z_scut*mm));
