% S16_COMPRESOR  Compresorul electric și admisia: aerul, presiunea, roata, motorul, galeria.
% Dimensiunile vin din compresor.m; Fusion le construiește în pașii 12 (corpul cilindrului) și 13.
P = parametri();
C = compresor(P);
M = isg_geometrie(P);
mm = 1e3;
fprintf('\n=== S16 Compresorul electric și admisia ===\n');
fprintf('Aerul la %d rot/min: %.0f mg reținuți pe ciclu (umplere %.2f), livrare %.2f -> %.1f g/s\n', ...
        P.n_putere, C.m_ret*1e6, C.CE, C.DR, C.mdot*1e3);
fprintf('Galeria la %.2f bar (raport de presiune %.2f), aerul la %.0f °C; benzina injectată în transfer îl mai răcește cu până la %.0f K\n', ...
        C.p_s/1e5, C.PR, C.T_s - 273.15, C.dT_vap);
fprintf('Roata: Ø%.1f mm (intrare Ø%.1f, butuc Ø%.1f, ieșire %.1f mm), %.0f rot/min, %.0f m/s; %.0f W pe roată, %.0f W din baterie (%.0f A la %.0f V)\n', ...
        C.D2*mm, C.D1*mm, C.D_butuc*mm, C.b2*mm, P.n_comp, C.u2, C.P_c, C.P_e, C.P_e/(P.n_cel*P.V_cel_nom), P.n_cel*P.V_cel_nom);
fprintf('Motorul: %.3f N m nominal, rotor Ø%.1f x %.1f mm; inerția %.2f g cm2\n', C.T_n, 2*C.r_mot*mm, C.L_mot*mm, C.J*1e7);
fprintf('Colectorul, turnat cu cilindrul: planul la x = %.1f mm, axa la z = %.1f mm, inel R%.1f (±%.0f mm lățime), canal de %.0f mm spre galerie; iese %.0f mm în spatele cilindrului\n', ...
        C.x_c*mm, C.z_c*mm, C.R_sp*mm, C.R_sp_ext*mm, C.L_iesire*mm, C.lungime_spate*mm);
fprintf('Galeria %.0f cm3 (%.2f din cilindree)\n', C.V_gal*1e6, C.V_gal/P.Vd);

verifica(C.PR <= P.PR_max, 'K1', sprintf( ...
         'Livrarea %.2f trece prin ferestrele de transfer cu %.2f bar în galerie: raport %.2f <= %.1f (o treaptă, fără răcitor)', ...
         C.DR, C.p_s/1e5, C.PR, P.PR_max));
verifica(C.Ns >= 0.6 && C.Ns <= 0.9 && C.u2 <= P.u2_max && C.M1 <= 0.9 && C.DN <= P.DN_max, 'K2', sprintf( ...
         'Roata: viteza specifică %.2f (0,6-0,9: randament bun), %.0f m/s <= %.0f, Mach la intrare %.2f <= 0,9, DN %.2g <= %.2g', ...
         C.Ns, C.u2, P.u2_max, C.M1, C.DN, P.DN_max));
T_cont = M.T_max(2)*P.J_cont/P.J_max;                   % cuplul continuu al mașinii de pe arbore, la cald
P_isg = T_cont*P.n_putere*pi/30*P.eta_em_c;
verifica(C.P_e <= P_isg, 'K3', sprintf( ...
         'Mașina de pe arbore alimentează compresorul continuu: %.0f W cerut <= %.0f W (%.1f N m continuu la %d rot/min); %.1f%% din puterea motorului', ...
         C.P_e, P_isg, T_cont, P.n_putere, 100*C.P_e/(P.imep_plin*P.Vd*P.n_putere/60)));
verifica(C.t_pornire <= P.t_pornire_max, 'K4', sprintf( ...
         'De la oprit la %d rot/min în %.2f s <= %.2f s (cuplu de vârf de %g ori cel nominal)', ...
         P.n_comp, C.t_pornire, P.t_pornire_max, P.k_supra_c));
verifica(C.V_gal >= P.Vd && all(C.A_canal >= 1.1*C.A_fereastra) && C.v_admisie <= 50, 'K5', sprintf( ...
         'Galeria %.0f cm3 >= cilindreea; canalele A/B/C au %.2f/%.2f/%.2f din aria ferestrei (>= 1,1); racordul %.0f m/s <= 50', ...
         C.V_gal*1e6, C.A_canal./C.A_fereastra, C.v_admisie));
% Pereții dintre canale, prezoane și conducta de evacuare
pz = P.prezon_raza*[cosd(P.prezon_unghi) sind(P.prezon_unghi); cosd(180 - P.prezon_unghi) sind(180 - P.prezon_unghi)];
pz = [pz; pz(:,1) -pz(:,2)];
perete = inf;
for k = 1:3
    for s = [1 -1]
        u = s*P.tr_unghi(k)*pi/180;  e = [cos(u) sin(u)];  t = [-sin(u) cos(u)];
        for j = 1:size(pz, 1)
            q = pz(j,:);  r = q*e';  w = q*t';
            d = hypot(max([C.R_cam - r, 0, r - C.R_canal]), max(abs(w) - P.tr_latime(k)/2, 0));
            perete = min(perete, d - P.prezon_trecere/2);
        end
    end
end
p_ev = min(abs(pz(:,2))) - P.prezon_trecere/2 - P.w_ev/2;
% Corpul (Ø2 R_corp) e mai lat decât carterul: jos, în dreptul paharului rotorului, laturile se
% teșesc plan la fața carterului; degajarea trebuie să rămână în banda plină de sub galerie
z_deg = P.r_rot + P.t_pahar + P.joc_con;
% Compresorul în linie: nu lărgește motorul, canalul spre galerie e scurt, stă în spatele carterului
x_fata = C.x_c + P.D_admisie/2 + P.t_carcasa_c;          % fața inelului spre cilindru
z_jos_c = C.z_c - C.R_sp_ext;
Gc = geometrie_carter(P);
verifica(C.R_sp_ext <= P.R_corp && C.L_iesire <= 40e-3 && x_fata <= -(P.gat_lat/2 + P.joc_comp) && z_jos_c >= 0 ...
         && C.R_sp_ext < Gc.y_ext + P.joc_con, 'K7', sprintf( ...
         ['Compresorul în linie: ±%.0f mm lățime (cilindrul ±%.0f), canal de %.0f mm spre galerie (<= 40), ' ...
          'fața inelului la x = %.0f mm, în spatele carterului (%.0f), cel mai jos la %.0f mm, deasupra băii din spate'], ...
         C.R_sp_ext*mm, P.R_corp*mm, C.L_iesire*mm, x_fata*mm, -(P.gat_lat/2 + P.joc_comp)*mm, z_jos_c*mm));
verifica(min(perete, p_ev) >= P.perete_min && z_deg <= C.z_g(1), 'K6', sprintf( ...
         ['Pereți de %.1f mm între canale și prezoane, %.1f mm între evacuare și prezoane (>= %.0f mm); ' ...
          'laturile corpului, plane la fața carterului până la %.1f mm (rotorul + joc), sub galerie (%.0f mm)'], ...
         perete*mm, p_ev*mm, P.perete_min*mm, z_deg*mm, C.z_g(1)*mm));
