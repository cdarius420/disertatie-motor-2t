% S15_MASINA_ELECTRICA  Mașina electrică de pe arbore: stator, bobine, rotor (pasul 10 din Fusion).
% Dimensionarea e în isg_geometrie.m; aici sunt rezultatele și verificările.
P = parametri();
I = isg_constante(P);
G = isg_geometrie(P);
fprintf('\n=== S15 Mașina electrică: %d crestături, %d poli, rotor exterior de oțel ===\n', P.Q_isg, 2*P.p_isg);
mm = 1e3;
fprintf('Înfășurarea: %s; factor %.3f; %d spire pe bobină, %d în serie pe fază\n', strjoin(G.faze, ' '), G.kw, G.N_c, G.N_s);
fprintf('Întrefier: Ø%.1f mm, inducție %.2f T (20 °C) / %.2f T (%d °C), fundamentala %.2f / %.2f T\n', ...
        G.D_g*mm, G.Bg, P.T_mag, G.B1);
fprintf('Pachet %.1f mm (tole de %.1f mm); stator Ø%.1f/Ø%.1f mm, dinți de %.1f mm, fundul crestăturii la R%.1f mm\n', ...
        G.L*mm, P.tola*mm, 2*G.R_s*mm, 2*G.R_si*mm, G.b_t*mm, G.R_fund*mm);
fprintf('Crestătura: %.0f mm2, %.1f A/mm2 la %d A (scurtă durată), umplere %.2f; capetele bobinelor ies %.1f mm\n', ...
        G.A_cresta*1e6, G.J_cresta/1e6, P.I_pk, P.k_umplere, G.capete*mm);
fprintf('Cuplul la %d A: %.1f N m cu magneții reci, %.1f N m la %d °C; forfecare în întrefier %.1f kPa\n', ...
        P.I_pk, G.T_max, P.T_mag, G.forfecare/1e3);
fprintf('Frecvența la %d rot/min: %.0f Hz\n', P.n_supra, G.f_supra);
fprintf('Rotorul: %.2f kg (magneți %.0f g), inerție %.5f kg m2; cu arborele: %.5f kg m2 (volantul clasic: %.3f)\n', ...
        G.m_rotor, G.m_magneti*1e3, G.J_rotor, G.J_rotor + echilibrare(P).J, P.J_pasiv);

verifica(G.k_e(1) <= I.k && G.k_e(1) >= 0.97*I.k, 'I1', sprintf( ...
         'Constanta de tensiune cu magneții reci %.5f V s/rad: sub regula bateriei (%.5f) cu cel mult 3%%', G.k_e(1), I.k));
verifica(G.t_pahar_nec <= P.t_pahar, 'I2', sprintf('Paharul de %.1f mm închide fluxul (are nevoie de %.1f mm la %.1f T)', ...
         P.t_pahar*mm, G.t_pahar_nec*mm, P.B_max(3)));
verifica(G.R_si - P.ureche_stator(1) >= P.R_butuc + 2e-3, 'I3', sprintf( ...
         'Statorul (Ø%.1f, urechile la R%.1f) trece peste butucul de R%.0f mm cu %.1f mm', ...
         2*G.R_si*mm, (G.R_si - P.ureche_stator(1))*mm, P.R_butuc*mm, (G.R_si - P.ureche_stator(1) - P.R_butuc)*mm));
verifica(G.H_a <= 0.5*G.Hcj, 'I4', sprintf('Magneții nu se demagnetizează: %.0f kA/m la %d A <= jumătate din Hcj la %d °C (%.0f kA/m)', ...
         G.H_a/1e3, P.I_pk, P.T_mag, G.Hcj/1e3));
verifica(G.forfecare <= 40e3, 'I5', sprintf('Forfecarea în întrefier %.1f kPa <= 40 kPa (scurtă durată, răcire prin capac)', G.forfecare/1e3));
